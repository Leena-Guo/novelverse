const MATCHERS = GENRES.map((g) => ({
  tag: g.tag,
  re: new RegExp(g.kw.map((k) => k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'i'),
}));

/** 从书名/简介中抽取题材标签（返回标签数组，按词表顺序） */
export function extractTags(title, intro = '') {
  const text = `${title || ''} ${intro || ''}`;
  if (!text.trim()) return [];
  const out = [];
  for (const g of GENRES) {
    if (g.kw.some((k) => text.toLowerCase().includes(String(k).toLowerCase()))) out.push(g.tag);
  }
  return out;
}

/** 存库用：以 |标签| 形式包裹，便于 LIKE '%|标签|%' 精确匹配 */
export function tagsToField(tags) {
  return tags && tags.length ? `|${tags.join('|')}|` : '';
}
