export function ensureSeed() {
  const n = get('SELECT COUNT(*) AS n FROM books').n;
  if (n > 0) return { seeded: false, books: n };
  for (const b of BOOKS) {
    const id = upsertBook('本地书库', {
      source_id: b.source_id,
      title: b.title,
      author: b.author,
      category: b.category,
      category_code: b.category_code,
      status: b.status,
      intro: b.intro,
      cover: '',
      latest_chapter: b.chapters[b.chapters.length - 1].title,
    }, { hot: 500 });
    b.chapters.forEach((c, i) => {
      const info = run(
        'INSERT OR IGNORE INTO chapters(book_id, idx, title, source_ref, cached, word_count) VALUES(?,?,?,?,1,?)',
        id,
        i + 1,
        c.title,
        `${b.source_id}-${i + 1}`,
        c.paragraphs.join('').length,
      );
      const chId = get('SELECT id FROM chapters WHERE book_id=? AND idx=?', id, i + 1).id;
      run(
        'INSERT OR REPLACE INTO chapter_contents(chapter_id, content) VALUES(?,?)',
        chId,
        JSON.stringify(c.paragraphs),
      );
    });
    run('UPDATE books SET chapter_count=?, enriched=1 WHERE id=?', b.chapters.length, id);
  }
  return { seeded: true, books: BOOKS.length };
}
